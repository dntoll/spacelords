// arkitekturkarta: draws docs/architecture/*.puml from architecture.config.mjs
// and the actual imports in src/. Run without arguments to write the diagrams
// and with --check to fail when they are out of date.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { featureModules, shellAreas } from '../architecture.config.mjs';

const p = path.posix;
const root = fileURLToPath(new URL('..', import.meta.url));
export const outputDirectory = 'docs/architecture';
const header = [
  "' Generated by scripts/architecture-map.mjs from architecture.config.mjs and",
  "' the imports in src/. Do not edit by hand; run npm run architecture:map.",
];
const layers = ['controllers', 'models', 'views'];
const sharedCase = '(delat)';

function sourceFiles() {
  return readdirSync(path.join(root, 'src'), { recursive: true })
    .map((file) => `src/${String(file).replaceAll('\\', '/')}`)
    .filter((file) => file.endsWith('.ts') && !file.endsWith('.d.ts'))
    .sort();
}

const statement =
  /^\s*(?:import|export)\s+(type\s+)?([^;]*?)\s*from\s*'(\.{1,2}\/[^']+)'/gm;

function imports(file, fileSet) {
  const text = readFileSync(path.join(root, file), 'utf8');
  const found = [];
  for (const [, typeKeyword, clause, spec] of text.matchAll(statement)) {
    const target = p
      .normalize(p.join(p.dirname(file), spec))
      .replace(/\.js$/, '.ts');
    if (!fileSet.has(target)) continue;
    const names = /\{([^}]*)\}/.exec(clause)?.[1].split(',') ?? [];
    const typeOnly =
      Boolean(typeKeyword) ||
      (names.length > 0 &&
        !/^[\w$]/.test(clause.trim()) &&
        names.every((name) => !name.trim() || name.trim().startsWith('type ')));
    found.push({ target, typeOnly });
  }
  return found;
}

const areas = [...shellAreas, ...featureModules];
function unitOf(file) {
  if (file === 'src/client/main.ts') return 'main';
  const client = /^src\/client\/([^/]+)\//.exec(file);
  if (client)
    return areas.some(({ dir }) => dir === client[1]) ? client[1] : 'client';
  return file.split('/')[1];
}

const id = (text) => text.replace(/[^A-Za-z0-9]/g, '_');
const quote = (text) => `"${text.replaceAll('"', "'")}"`;

class Edges {
  #edges = new Map();
  add(from, to, label, typeOnly) {
    const key = `${from}\u0000${to}`;
    const edge = this.#edges.get(key) ?? {
      from,
      to,
      labels: new Set(),
      typeOnly: true,
      count: 0,
    };
    if (label) edge.labels.add(label);
    edge.typeOnly &&= typeOnly;
    edge.count += 1;
    this.#edges.set(key, edge);
  }
  lines(withCount) {
    return [...this.#edges.values()]
      .sort((a, b) => `${a.from} ${a.to}`.localeCompare(`${b.from} ${b.to}`))
      .map(({ from, to, labels, typeOnly, count }) => {
        const parts = [...labels].sort();
        if (withCount) parts.push(`${count}`);
        if (typeOnly) parts.push('typer');
        return `${id(from)} ${typeOnly ? '..>' : '-->'} ${id(to)}${parts.length ? ` : ${parts.join(', ')}` : ''}`;
      });
  }
}

function targetLabel(target) {
  const relative = target.replace(/^src\/client\//, '');
  const module = featureModules.find(({ dir }) =>
    relative.startsWith(`${dir}/`),
  );
  if (module) return relative.split('/')[1];
  return p.basename(target, '.ts');
}

function overview(graph) {
  const edges = new Edges();
  for (const [file, found] of graph) {
    const from = unitOf(file);
    for (const { target, typeOnly } of found) {
      const to = unitOf(target);
      if (to !== from) edges.add(from, to, targetLabel(target), typeOnly);
    }
  }
  const node = (unit, title, description) =>
    `  rectangle ${quote(`${title}\\n<size:10>${description}</size>`)} as ${id(unit)}`;
  return [
    '@startuml',
    ...header,
    'title Spacelords – kodkarta, nivå 1: moduler och beroenden',
    'skinparam packageStyle rectangle',
    'skinparam shadowing false',
    'package "src/client" {',
    node('main', 'main.ts', 'Startpunkt som skapar skal och kartvyer'),
    ...shellAreas.map(({ dir, title, description }) =>
      node(dir, `${title}\\n${dir}/`, description),
    ),
    ...featureModules.map(({ dir, title, description }) =>
      node(dir, `${title}\\n${dir}/`, description),
    ),
    '}',
    'package "src/shared" {',
    node('shared', 'Shared', 'Format som klient och server delar'),
    '}',
    'package "src/server" {',
    node(
      'server',
      'Server',
      'Express, hälsokontroll och bordningskartornas API',
    ),
    '}',
    ...edges.lines(false),
    'legend right',
    '  Pilar visar faktiska importer. Etiketten anger vilka index-filer',
    '  (models, views, controllers) eller filer som används.',
    '  Streckad pil: bara typimporter.',
    '  Detaljer per modul: <modul>.puml i samma katalog.',
    'endlegend',
    '@enduml',
    '',
  ].join('\n');
}

function caseOf(relative) {
  const parts = relative.split('/');
  if (parts.length <= 2) return sharedCase;
  return parts[1];
}

function moduleDiagram(area, graph) {
  const prefix = `src/client/${area.dir}/`;
  const isFeature = featureModules.includes(area);
  const own = [...graph.keys()].filter((file) => file.startsWith(prefix));
  const cases = new Map();
  const nodeOf = (file) => {
    const relative = file.slice(prefix.length);
    const layer = relative.includes('/') ? relative.split('/')[0] : sharedCase;
    return { kase: caseOf(relative), layer };
  };
  const publicSurface = new Map();
  for (const file of own) {
    const relative = file.slice(prefix.length);
    if (/^(controllers|models|views)\/index\.ts$/.test(relative)) {
      const exported = graph
        .get(file)
        .map(({ target }) => p.basename(target, '.ts'));
      publicSurface.set(relative.split('/')[0], [...new Set(exported)].sort());
      continue;
    }
    const { kase, layer } = nodeOf(file);
    const byLayer = cases.get(kase) ?? new Map();
    byLayer.set(layer, [
      ...(byLayer.get(layer) ?? []),
      p.basename(file, '.ts'),
    ]);
    cases.set(kase, byLayer);
  }
  const caseId = (kase) => `${area.dir}__${kase}`;
  const layerId = (kase, layer) => `${caseId(kase)}__${layer}`;
  const internal = new Edges();
  const crossCase = new Edges();
  const external = new Edges();
  const externals = new Map();
  for (const file of own) {
    if (file.endsWith('/index.ts')) continue;
    const from = nodeOf(file);
    for (const { target, typeOnly } of graph.get(file)) {
      if (target.startsWith(prefix)) {
        const to = nodeOf(target);
        if (to.kase === from.kase) {
          if (to.layer !== from.layer)
            internal.add(
              layerId(from.kase, from.layer),
              layerId(to.kase, to.layer),
              '',
              typeOnly,
            );
        } else crossCase.add(caseId(from.kase), caseId(to.kase), '', typeOnly);
      } else {
        const unit = unitOf(target);
        // Every module uses the shell and common/; the overview shows that.
        if (isFeature && shellAreas.some(({ dir }) => dir === unit)) continue;
        const label = targetLabel(target);
        const externalId = `ext__${unit}`;
        externals.set(externalId, unit);
        external.add(caseId(from.kase), externalId, label, typeOnly);
      }
    }
  }
  const sortedCases = [...cases.keys()].sort((a, b) =>
    a === sharedCase ? -1 : b === sharedCase ? 1 : a.localeCompare(b),
  );
  const order = (layer) => {
    const index = layers.indexOf(layer);
    return index < 0 ? layers.length : index;
  };
  const casePackages = sortedCases.flatMap((kase) => {
    const byLayer = cases.get(kase);
    return [
      `package ${quote(kase)} as ${id(caseId(kase))} {`,
      ...[...byLayer.keys()]
        .sort((a, b) => order(a) - order(b) || a.localeCompare(b))
        .map(
          (layer) =>
            `  rectangle ${quote(`<b>${layer}</b>\\n${byLayer.get(layer).sort().join('\\n')}`)} as ${id(layerId(kase, layer))}`,
        ),
      '}',
    ];
  });
  const surface = publicSurface.size
    ? [
        'package "Publik yta (index.js)" as public_surface #FFFFEE {',
        ...[...publicSurface.keys()]
          .sort((a, b) => order(a) - order(b))
          .map(
            (layer) =>
              `  rectangle ${quote(`<b>${layer}/index.js</b>\\n${publicSurface.get(layer).join('\\n')}`)} as ${id(`public__${layer}`)}`,
          ),
        '}',
      ]
    : [];
  const externalNodes = [...externals.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([externalId, unit]) =>
        `rectangle ${quote(unit)} as ${id(externalId)} #EEEEEE`,
    );
  return [
    '@startuml',
    ...header,
    `title Spacelords – kodkarta, nivå 2: ${area.title} (src/client/${area.dir}/)`,
    'skinparam packageStyle rectangle',
    'skinparam shadowing false',
    'left to right direction',
    `note as about\n  ${area.description}\n  Paket = fall. ${sharedCase} = filer direkt under lagret.\n  Pilar mellan fall visar antal importer.\n${isFeature ? '  Beroenden på app/ och common/ visas i overview.puml.\n' : ''}end note`,
    ...surface,
    ...casePackages,
    ...externalNodes,
    ...internal.lines(false),
    ...crossCase.lines(true),
    ...external.lines(false),
    '@enduml',
    '',
  ].join('\n');
}

export function buildDiagrams() {
  const files = sourceFiles();
  const fileSet = new Set(files);
  const graph = new Map(files.map((file) => [file, imports(file, fileSet)]));
  const diagrams = new Map([
    [`${outputDirectory}/overview.puml`, overview(graph)],
  ]);
  for (const area of areas.filter(({ dir }) => dir !== 'common'))
    diagrams.set(
      `${outputDirectory}/${area.dir}.puml`,
      moduleDiagram(area, graph),
    );
  return diagrams;
}

export function staleDiagrams() {
  const stale = [];
  for (const [file, content] of buildDiagrams()) {
    let current = '';
    try {
      current = readFileSync(path.join(root, file), 'utf8').replaceAll(
        '\r\n',
        '\n',
      );
    } catch {
      // A missing diagram is stale.
    }
    if (current !== content) stale.push(file);
  }
  return stale;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  if (process.argv.includes('--check')) {
    const stale = staleDiagrams();
    if (stale.length) {
      console.error(
        `Out of date: ${stale.join(', ')}. Run npm run architecture:map.`,
      );
      process.exitCode = 1;
    }
  } else {
    mkdirSync(path.join(root, outputDirectory), { recursive: true });
    for (const [file, content] of buildDiagrams()) {
      writeFileSync(path.join(root, file), content);
      console.log(`wrote ${file}`);
    }
  }
}
